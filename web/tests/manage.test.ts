import assert from "node:assert/strict";
import { managementForms, upgradeForm } from "../src/manage";
const legacy = managementForms("entry", 1);
assert.doesNotMatch(legacy, /id="delete-entry"|id="rename-form"/);
assert.match(legacy, /格式 2/);
const active = managementForms('"><img src=x onerror=alert(1)>', 2);
assert.doesNotMatch(active, /<img\b/);
assert.match(active, /&lt;img/);
assert.match(active, /不是安全擦除/);
assert.match(active, /maxlength="160"/);
const upgrade = upgradeForm(1);
assert.match(upgrade, /type="password" autocomplete="current-password"/);
assert.match(upgrade, /id="upgrade-confirmed" type="checkbox" required/);
assert.doesNotMatch(upgrade, /\bchecked\b/);
assert.match(upgrade, /暂停其他设备写入/);
assert.match(upgrade, /旧程序不能打开格式 2/);
assert.doesNotMatch(upgradeForm(2), /id="upgrade-form"/);
console.log("Management form and explicit migration consent tests passed.");
